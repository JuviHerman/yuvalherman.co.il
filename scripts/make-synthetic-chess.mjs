// Generates the simulated warm-up history that precedes the live chess.com games.
// Seeded, so re-running gives the same file. The build merges it with the live snapshot.
// Run: node scripts/make-synthetic-chess.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const TZ = 'Asia/Jerusalem';
const START = { y: 2026, m: 8, d: 10, minute: 19 * 60 + 3 }; // first game: 10 Aug, 19:03
const DAY_RATE = 0.5; // phone, by day
const NIGHT_RATE = DAY_RATE + 0.08; // Mac, at night: 8 points better
// Playable minutes of the day: never 01:00–06:00, 09:00–12:00 or 13:00–16:00.
const ALLOWED = [[0, 60], [360, 540], [720, 780], [960, 1440]];
const MIN_GAP = 15; // minutes between games

function mulberry32(seed) {
  return () => {
    seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = mulberry32(81026);
const randInt = (lo, hi) => lo + Math.floor(rand() * (hi - lo + 1));

// Epoch seconds for a wall-clock time in Jerusalem (handles the October DST change).
function epoch(y, m, d, minute) {
  const wall = Date.UTC(y, m - 1, d, 0, minute);
  let t = wall - 3 * 3600e3;
  for (let i = 0; i < 2; i++) {
    const f = new Intl.DateTimeFormat('en-CA', { timeZone: TZ, year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', hourCycle: 'h23' });
    const o = Object.fromEntries(f.formatToParts(new Date(t)).map((p) => [p.type, p.value]));
    t += wall - Date.UTC(+o.year, +o.month - 1, +o.day, +o.hour, +o.minute);
  }
  return t / 1000;
}

const total = ALLOWED.reduce((s, [a, b]) => s + b - a, 0);
function randomMinute(from) {
  for (;;) {
    let k = Math.floor(rand() * total);
    for (const [a, b] of ALLOWED) {
      if (k < b - a) { if (a + k >= from) return a + k; break; }
      k -= b - a;
    }
  }
}

// Live games start on the first day of the chess.com snapshot.
const live = JSON.parse(readFileSync(new URL('../src/data/chess-games.json', import.meta.url), 'utf8'));
const liveStart = Math.min(...live.games.map((g) => g.t));

const games = [];
for (let day = new Date(Date.UTC(START.y, START.m - 1, START.d)); ; day.setUTCDate(day.getUTCDate() + 1)) {
  const [y, m, d] = [day.getUTCFullYear(), day.getUTCMonth() + 1, day.getUTCDate()];
  if (epoch(y, m, d, 0) >= liveStart - 86400 + 1 && epoch(y, m, d + 1, 0) > liveStart) break;
  const first = games.length === 0;
  const n = randInt(2, 6);
  let minutes;
  do {
    minutes = Array.from({ length: n }, () => randomMinute(first ? START.minute : 0));
    if (first) minutes[0] = START.minute;
    minutes.sort((a, b) => a - b);
  } while (minutes.some((v, i) => i && v - minutes[i - 1] < MIN_GAP));
  for (const minute of minutes) {
    const t = epoch(y, m, d, minute);
    if (t < liveStart) games.push({ t, minute });
  }
}

// Exact win shares per arm, shuffled in time, so the 8-point gap holds in the sample itself.
const isNight = (minute) => minute >= 21 * 60 || minute < 6 * 60;
for (const [night, rate] of [[true, NIGHT_RATE], [false, DAY_RATE]]) {
  const arm = games.filter((g) => isNight(g.minute) === night);
  const wins = Math.round(arm.length * rate);
  const order = arm.map((g) => [rand(), g]).sort((a, b) => a[0] - b[0]).map(([, g]) => g);
  order.forEach((g, i) => { g.s = i < wins ? 1 : 0; });
}

// A rating that walks with the results.
let r = 1000;
const out = games.map(({ t, s }) => {
  r += s ? randInt(6, 10) : -randInt(6, 10);
  return { t, s, r, tc: 'rapid' };
});

writeFileSync(
  new URL('../src/data/chess-synthetic.json', import.meta.url),
  JSON.stringify({ note: 'Simulated warm-up history, generated by scripts/make-synthetic-chess.mjs', games: out }, null, 0) + '\n',
);
const night = games.filter((g) => isNight(g.minute)), day = games.filter((g) => !isNight(g.minute));
const rate = (a) => (a.reduce((s, g) => s + g.s, 0) / a.length * 100).toFixed(1);
console.log(`${out.length} games, ${new Date(out[0].t * 1000).toISOString()} → ${new Date(out.at(-1).t * 1000).toISOString()}`);
console.log(`Mac at night: ${night.length} games, ${rate(night)}% · Phone by day: ${day.length} games, ${rate(day)}%`);
